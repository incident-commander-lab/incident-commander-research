"""The shop's AI feature: "Ask about this product", answered by an LLM.

POST /assistant/ask {"product_id": 1, "question": "..."} reads the product from Juice Shop's own API
and asks the chat model (Ollama). On AWS the model runs on the GPU node, so user load drives GPU
utilisation; locally it runs on the Mac.

The release is the Deployment's environment, so a bad release is a real Kubernetes rollout and
`kubectl rollout undo` really reverts it:
  NUM_CTX          context window asked of the model per request (the GPU-memory fault raises it)
  MAX_CONCURRENCY  requests sent to the model at once; the rest wait in a queue (rate limit)
  RETAIN_ANSWERS   "true" keeps every answer in memory (the memory-leak fault)
"""
from __future__ import annotations

import asyncio
import os
import time

import httpx
from fastapi import FastAPI, HTTPException
from fastapi.responses import PlainTextResponse
from prometheus_client import CONTENT_TYPE_LATEST, Counter, Gauge, Histogram, Info, generate_latest
from pydantic import BaseModel, Field

SHOP = os.environ.get("SHOP_URL", "http://juice-shop.shop.svc:3000")
OLLAMA = os.environ.get("OLLAMA_URL", "http://host.k3d.internal:11434")
MODEL = os.environ.get("CHAT_MODEL", "qwen3:1.7b")
VERSION = os.environ.get("ASSISTANT_VERSION", "1.0.0")
NUM_CTX = int(os.environ.get("NUM_CTX", "2048"))
MAX_CONCURRENCY = int(os.environ.get("MAX_CONCURRENCY", "4"))
RETAIN = os.environ.get("RETAIN_ANSWERS", "false").lower() == "true"
TIMEOUT = float(os.environ.get("MODEL_TIMEOUT_S", "120"))

REQS = Counter("assistant_requests_total", "Questions answered", ["status"])
LAT = Histogram("assistant_request_seconds", "End-to-end answer time",
                buckets=(0.5, 1, 2, 4, 8, 15, 30, 60, 120))
INFLIGHT = Gauge("assistant_inflight", "Requests being answered by the model now")
QUEUED = Gauge("assistant_queue_depth", "Requests waiting for a model slot")
TOKENS = Counter("assistant_tokens_total", "Tokens generated by the chat model")
RETAINED = Gauge("assistant_retained_bytes", "Bytes of answers kept in memory")
Info("assistant_release", "Running release").info(
    {"version": VERSION, "num_ctx": str(NUM_CTX), "max_concurrency": str(MAX_CONCURRENCY), "retain": str(RETAIN)})

app = FastAPI(title="Shop assistant")
_slots = asyncio.Semaphore(MAX_CONCURRENCY)
_kept: list[bytes] = []
_client = httpx.AsyncClient(timeout=TIMEOUT)


class Ask(BaseModel):
    product_id: int = Field(ge=1)
    question: str = Field(min_length=1, max_length=500)


@app.post("/assistant/ask")
async def ask(q: Ask):
    t0 = time.monotonic()
    try:
        r = await _client.get(f"{SHOP}/api/Products/{q.product_id}")
        if r.status_code != 200:
            REQS.labels("no_product").inc()
            raise HTTPException(404, "unknown product")
        p = r.json().get("data", {})
        prompt = (f"Product: {p.get('name')}\nPrice: {p.get('price')}\nDescription: {p.get('description')}\n\n"
                  f"Customer question: {q.question}\nAnswer in two or three sentences, using only the product facts.")
        QUEUED.inc()
        async with _slots:
            QUEUED.dec()
            INFLIGHT.inc()
            try:
                m = await _client.post(f"{OLLAMA}/api/chat", json={
                    "model": MODEL, "stream": False, "think": False,
                    "messages": [{"role": "user", "content": prompt}],
                    "options": {"num_ctx": NUM_CTX, "temperature": 0.3, "num_predict": 160}})
            finally:
                INFLIGHT.dec()
        if m.status_code != 200:
            REQS.labels("model_error").inc()
            raise HTTPException(502, f"model error {m.status_code}")
        body = m.json()
        answer = body.get("message", {}).get("content", "")
        TOKENS.inc(body.get("eval_count", 0))
        if RETAIN:   # the leak: every answer, padded like a cached rendering, is kept forever
            _kept.append(answer.encode() + b" " * 1_000_000)
            RETAINED.set(sum(map(len, _kept)))
        REQS.labels("ok").inc()
        return {"product": p.get("name"), "answer": answer, "release": VERSION}
    except httpx.HTTPError as e:
        REQS.labels("upstream_error").inc()
        raise HTTPException(503, f"upstream unavailable: {type(e).__name__}")
    finally:
        LAT.observe(time.monotonic() - t0)


@app.get("/assistant/healthz")
async def healthz():
    return {"ok": True, "release": VERSION, "model": MODEL}


@app.get("/metrics")
async def metrics():
    return PlainTextResponse(generate_latest(), media_type=CONTENT_TYPE_LATEST)
